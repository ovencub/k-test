def src(name, url):
    return {"name": name, "url": url}

def N(id, cat, title, question, answer, unit, smin, smax, step, myth, expl, caveat, source, year, ver="verified", hint=None, note=None, tol=None):
    Q.append(dict(id=id, type="number", category=cat, title=title, question=question,
                  answer=answer, unit=unit, slider=dict(min=smin, max=smax, step=step),
                  hint=hint, myth=myth, explanation=expl, caveat=caveat,
                  source=source, dataYear=year, verification=ver, note=note, tolerance=tol))

def P(id, cat, title, question, slices, myth, expl, caveat, source, year, ver="verified", note=None):
    Q.append(dict(id=id, type="pie", category=cat, title=title, question=question,
                  slices=[dict(label=l, value=v) for l, v in slices], unit="%",
                  myth=myth, explanation=expl, caveat=caveat,
                  source=source, dataYear=year, verification=ver, note=note))

def L(id, cat, title, question, points, cutoff, unit, ymin, ymax, myth, expl, caveat, source, year, ver="partial", note=None):
    Q.append(dict(id=id, type="line", category=cat, title=title, question=question,
                  series=[dict(x=x, y=y) for x, y in points], cutoffX=cutoff, unit=unit,
                  yRange=[ymin, ymax], myth=myth, explanation=expl, caveat=caveat,
                  source=source, dataYear=year, verification=ver, note=note))

