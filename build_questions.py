# 신규 형식
#   bar          : bars[{label,value,hidden}]  가려진 막대 높이 맞추기 (음수 허용, yRange)
#   bubble       : items[{label,value,hidden}] 가려진 원 크기(면적) 맞추기 — 크기 차이가 큰 비교용
#   donut        : slices 2~4개, 합계 100     — 단일 비율·소수 범주
#   pie          : slices 4개 이상, 합계 100
#   distribution : bins[{label,value}] 순서 있는 구간, 합계 100 — 히스토그램 모양 그리기

def _bars(rows):
    return [dict(label=l, value=v, hidden=h) for l, v, h in rows]

def conv(qid, t, question=None, unit=None, ver=None, note=None, **fields):
    """기존 숫자/파이 문제를 다른 형식으로 전환"""
    q = next(x for x in Q if x["id"] == qid)
    for k in ("answer", "slider", "tolerance", "slices", "series", "cutoffX", "yRange", "bars", "items", "bins"):
        q.pop(k, None)
    q["type"] = t
    if question: q["question"] = question
    if unit is not None: q["unit"] = unit
    if ver: q["verification"] = ver
    if note: q["note"] = (q.get("note") + " / " if q.get("note") else "") + note
    if "bars" in fields: fields["bars"] = _bars(fields["bars"])
    if "items" in fields: fields["items"] = _bars(fields["items"])
    if "slices" in fields: fields["slices"] = [dict(label=l, value=v) for l, v in fields["slices"]]
    if "bins" in fields: fields["bins"] = [dict(label=l, value=v) for l, v in fields["bins"]]
    q.update(fields)

